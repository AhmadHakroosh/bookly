// Writes apps/web/src/server/editions/registry.generated.ts: static imports of the commercial
// modules installed under ee/ (ADR 0006). With ee/ deleted it writes an empty registry, so the
// AGPL core builds, tests and runs on its own. Run before dev, build, typecheck and test.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const eeDir = path.join(root, "ee");
const out = path.join(root, "apps/web/src/server/editions/registry.generated.ts");

const modules = existsSync(eeDir)
  ? readdirSync(eeDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => {
        const manifest = path.join(eeDir, d.name, "package.json");
        if (!existsSync(manifest)) return null;
        const entry = JSON.parse(readFileSync(manifest, "utf8")).bookly?.module;
        return entry ? path.join(eeDir, d.name, entry) : null;
      })
      .filter(Boolean)
      .sort()
  : [];

const rel = (file) =>
  path.relative(path.dirname(out), file).split(path.sep).join("/").replace(/\.ts$/, "");
const lines = [
  "// Generated by scripts/ee-registry.mjs. Do not edit. Empty when ee/ is absent.",
  'import type { EeModule } from "@bookly/editions";',
  ...modules.map((m, i) => `import m${i} from "${rel(m)}";`),
  "",
  `export const EE_MODULES: readonly EeModule[] = [${modules.map((_, i) => `m${i}`).join(", ")}];`,
  "",
];
const next = lines.join("\n");
// The folder holds only this generated file, so a fresh checkout does not have it yet.
mkdirSync(path.dirname(out), { recursive: true });
if (!existsSync(out) || readFileSync(out, "utf8") !== next) writeFileSync(out, next);
console.log(`[ee] registry: ${modules.length} module${modules.length === 1 ? "" : "s"}`);
